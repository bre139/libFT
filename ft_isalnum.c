int	ft_isalnum(int c)
{
	return ((c >= 'a' && c <= 'z')
		|| (c >= 'A' && c <= 'Z')
		|| (c >= '0' && c <= '9'));
}

/*
DESCRIPTION:
isalnum()
checks for an alphanumeric character;
it is equivalent to (isalpha(c) || isdigit(c)).
*/